// Builds situations-data.js from data/situation/ so the static page needs no fetch or backend.
// Usage: node docs/prototypes/situation-entry/build-data.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = join(here, '../../../data/situation');
const outFile = join(here, 'situations-data.js');

export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  const body = text.replace(/^﻿/, '');
  for (let i = 0; i < body.length; i += 1) {
    const ch = body[i];
    if (quoted) {
      if (ch === '"' && body[i + 1] === '"') { field += '"'; i += 1; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && body[i + 1] === '\n') i += 1;
      row.push(field); field = '';
      if (row.some((cell) => cell.trim() !== '')) rows.push(row);
      row = [];
    } else field += ch;
  }
  row.push(field);
  if (row.some((cell) => cell.trim() !== '')) rows.push(row);
  const [header, ...records] = rows;
  return records.map((cells) => Object.fromEntries(header.map((key, index) => [key.trim(), (cells[index] ?? '').trim()])));
}

// "(02)25156222" -> display "02-2515-6222", dial "0225156222"
export function normalizePhone(raw) {
  const digits = raw.replace(/\D/g, '');
  if (!/^02\d{8}$/.test(digits)) throw new Error(`Unexpected Taipei phone format: ${raw}`);
  return { dial: digits, display: `02-${digits.slice(2, 6)}-${digits.slice(6)}` };
}

export function buildData() {
  const base = JSON.parse(readFileSync(join(dataDir, 'situations.json'), 'utf8'));
  const welfareCenters = parseCsv(readFileSync(join(dataDir, 'social-welfare-centers.csv'), 'utf8')).map((row) => ({
    name: row['機構名稱'],
    district: row['行政區'],
    address: row['地址'],
    phone: normalizePhone(row['電話']),
  }));
  const laborConsult = parseCsv(readFileSync(join(dataDir, 'labor-lawyer-consultation.csv'), 'utf8')).map((row) => ({
    name: row['地點'],
    address: row['地址'],
    method: row['方式'],
    hours: row['時段'],
  }));
  return {
    ...base,
    directories: {
      welfareCenters: { title: '各區社會福利服務中心', sources: ['d5-welfare-centers'], rows: welfareCenters },
      laborConsult: { title: '免費勞工法令律師諮詢地點與時段', sources: ['d8-labor-lawyer'], rows: laborConsult },
    },
  };
}

export function renderModule(data) {
  return `// Generated by build-data.mjs from data/situation/. Do not edit by hand.\nwindow.SITUATION_DATA = ${JSON.stringify(data, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = renderModule(buildData());
  if (process.argv.includes('--check')) {
    if (readFileSync(outFile, 'utf8') !== output) {
      console.error('situations-data.js is stale; run node docs/prototypes/situation-entry/build-data.mjs');
      process.exit(1);
    }
    console.log('situations-data.js is up to date');
  } else {
    writeFileSync(outFile, output);
    console.log(`wrote ${outFile}`);
  }
}
